#!/usr/bin/env python3
"""Generate the signing keypair for OTA images.

ECDSA on P-256 with SHA-256. Asymmetric on purpose: the board holds only the
PUBLIC key, so dumping its flash - which anyone with the USB port can do -
gives an attacker no way to sign anything. A shared secret (an HMAC, say)
would be simpler and would be broken by the first person to read the chip.

Writes two files:

  ota_private_key.pem   THE SECRET. Gitignored. Lose it and you can no longer
                        sign updates for boards already in the field; leak it
                        and anyone can. Back it up somewhere other than this
                        working tree.

  ota_pubkey.h          The public key as a C string, committed to the repo
                        and compiled into the firmware. Public keys are
                        public; there is nothing to protect here.

Changing the key means re-flashing every board over USB, because a board only
accepts images signed by the key it already carries. That is the whole point,
and it is also why you should generate it once and keep the private key safe
rather than regenerating it casually.

Usage:
    python keygen.py [--force]
"""
import os
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

PRIV = os.path.join(REPO, "ota_private_key.pem")
PUBH = os.path.join(REPO, "ota_pubkey.h")

force = "--force" in sys.argv

if os.path.exists(PRIV) and not force:
    sys.exit("%s already exists.\nRefusing to overwrite it - generating a new "
             "key orphans every board in the field.\nPass --force if you are "
             "certain." % PRIV)

key = ec.generate_private_key(ec.SECP256R1())

priv_pem = key.private_bytes(
    encoding=serialization.Encoding.PEM,
    format=serialization.PrivateFormat.PKCS8,
    encryption_algorithm=serialization.NoEncryption(),
)
pub_pem = key.public_key().public_bytes(
    encoding=serialization.Encoding.PEM,
    format=serialization.PublicFormat.SubjectPublicKeyInfo,
)

with open(PRIV, "wb") as f:
    f.write(priv_pem)

lines = pub_pem.decode("ascii").strip().splitlines()
body = "\n".join('    "%s\\n"' % ln for ln in lines)

with open(PUBH, "w", encoding="utf-8", newline="\n") as f:
    f.write("""/*
  OTA image-signing public key. Generated by tools/keygen.py.

  Public by nature - this is committed deliberately. The matching private key
  is in ota_private_key.pem, which is gitignored and must stay that way.

  mbedtls_pk_parse_public_key() wants the terminating NUL counted in the
  length, which is why the sketch passes sizeof() rather than strlen().

  Replacing this key requires a USB flash of every board: a board only
  accepts images signed by the key it is already carrying, which is exactly
  the property that makes signing worth doing.
*/
#ifndef OTA_PUBKEY_H
#define OTA_PUBKEY_H

static const char OTA_PUBLIC_KEY_PEM[] =
%s;

#endif
""" % body)

print("wrote %s  (SECRET - gitignored, back it up)" % PRIV)
print("wrote %s  (public, commit this)" % PUBH)
print()
print("Boards must be USB-flashed once with this key before signed OTA works.")
